  /* a contact sheet of every sprite in the game, for reviewing the art */
  window.__soSheet = function (scale) {
    var SC = scale || 5, pad = 6;
    var rows = [];
    ["idle", "run", "jump", "fall", "duck", "hurt", "win"].forEach(function (pose) {
      rows.push(OUISSY[pose].small.concat(OUISSY[pose].big));
    });
    Object.keys(ART.skin).forEach(function (k) { rows.push(ART.skin[k]); });
    rows.push([ART.walkerSquash]);
    rows.push(ART.heart.concat(ART.power.grow, ART.power.star, ART.power.life,
                               ART.power.boost, ART.power.wing));
    Object.keys(ART.bosses).forEach(function (k) {
      rows.push(ART.bosses[k].calm.concat(ART.bosses[k].hurt));
    });
    var w = 0, h = 0;
    rows.forEach(function (r) {
      var rw = 0, rh = 0;
      r.forEach(function (i) { rw += i.width * SC + pad; rh = Math.max(rh, i.height * SC); });
      w = Math.max(w, rw); h += rh + pad * 2;
    });
    var o = document.createElement("canvas");
    o.width = w + 20; o.height = h + 20;
    var c = o.getContext("2d");
    c.imageSmoothingEnabled = false;
    c.fillStyle = "#4a6a8a"; c.fillRect(0, 0, o.width, o.height);
    var y = 10;
    rows.forEach(function (r) {
      var x = 10, tall = 0;
      r.forEach(function (img) {
        c.drawImage(img, x, y, img.width * SC, img.height * SC);
        x += img.width * SC + pad; tall = Math.max(tall, img.height * SC);
      });
      y += tall + pad * 2;
    });
    return o.toDataURL("image/png");
  };

  /* rescue.js borrows her sprite rather than keeping a second copy of her,
     so a change to her hair shows up in the story scenes too.

     NOT called `frame`. It was, and it is a function declaration at the same
     scope as the game loop's own frame(now) — so the later declaration won,
     requestAnimationFrame(frame) scheduled THIS instead, and the whole game
     rendered nothing: it fired once, returned a sprite, never rescheduled
     and never painted. No error, because asking for a sprite with a
     timestamp is perfectly legal. */
  function ouissyFrame(pose, k) {
    var set = OUISSY[pose] || OUISSY.idle;
    var arr = G && G.player && G.player.big ? set.big : set.small;
    return arr[Math.min(k || 0, arr.length - 1)];
  }

  return { start: start, stop: stop, frame: ouissyFrame, pause: function () { if (G && G.state === "play") togglePause(); } };
