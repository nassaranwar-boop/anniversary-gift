  /* =======================================================================
     THE FRAME DRIVER

     A fixed step keeps the physics identical on a 60Hz phone and a 144Hz
     monitor; whatever time is left over is carried into the next frame.
     ======================================================================= */
  var raf = null, lastT = 0, acc = 0;
  var STEP = 1 / 60, MAX_FRAME = 0.1;

  function frame(now) {
    raf = requestAnimationFrame(frame);
    if (!lastT) lastT = now;
    var dt = Math.min(MAX_FRAME, (now - lastT) / 1000);
    lastT = now;

    if (!onScreen()) return;

    /* the offline harness drives step() itself, so the loop only paints */
    if (window.__soTestDrive) { paint(now / 1000); return; }

    if (G.state === "cutscene") {
      /* the story module has the canvas. It is driven from this loop
         rather than one of its own, so there is still only ever one. */
      if (window.Rescue) {
        Rescue.step(Math.min(dt, 0.05));
        if (Rescue.done()) endCutscene();
      } else endCutscene();
    } else if (G.state === "play") {
      acc += dt;
      var guard = 0;
      while (acc >= STEP && guard++ < 6) { step(STEP); acc -= STEP; }
    } else {
      acc = 0;
      /* even paused, the world keeps breathing — sprites still animate, and
         with no level at all the menu scene is what is being painted */
      if (G.level) { stepParts(Math.min(dt, .05)); G.shake = Math.max(0, G.shake - dt * 26); }
    }
    paint(now / 1000);
  }

